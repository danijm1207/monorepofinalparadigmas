package edu.investigacion.application;

import edu.investigacion.domain.AppError;
import edu.investigacion.domain.Enums.CaseStatus;
import edu.investigacion.domain.Enums.Role;
import edu.investigacion.domain.Enums.State;
import edu.investigacion.domain.Models.Case;
import edu.investigacion.domain.Models.Page;
import edu.investigacion.domain.Models.User;
import edu.investigacion.domain.Repositories.CaseRepository;
import edu.investigacion.domain.Result;

import java.time.Instant;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

public final class CaseUseCase {
    private final CaseRepository caseRepository;

    public CaseUseCase(CaseRepository caseRepository) {
        this.caseRepository = caseRepository;
    }

    public Result<Page<Case>> list(
        User currentUser,
        int page,
        int limit,
        Optional<String> q,
        Optional<CaseStatus> status,
        Optional<Instant> from,
        Optional<Instant> to,
        Optional<UUID> requestedOwnerId
    ) {
        var pageRes = Validators.validatePagination(page, limit);
        if (pageRes.isFailure()) {
            return Result.fail(((Result.Failure<Void>) pageRes).error());
        }

        Optional<UUID> effectiveOwner = (currentUser.role() == Role.USER)
            ? Optional.of(currentUser.id())
            : requestedOwnerId;

        List<Case> cases = caseRepository.findAll(page, limit, q, status, from, to, effectiveOwner);
        long total = caseRepository.countAll(q, status, from, to, effectiveOwner);
        int totalPages = total == 0 ? 1 : (int) Math.ceil((double) total / limit);

        return Result.ok(new Page<>(cases, total, page, limit, totalPages));
    }

    public Result<Case> getById(User currentUser, UUID id) {
        Optional<Case> caseOpt = caseRepository.findById(id);
        if (caseOpt.isEmpty() || caseOpt.get().state() != State.ACTIVE) {
            return Result.fail(new AppError.NotFound("Caso no encontrado"));
        }

        Case c = caseOpt.get();
        if (!AccessPolicy.canAccessCase(currentUser, c.ownerId())) {
            return Result.fail(new AppError.NotFound("Caso no encontrado"));
        }

        return Result.ok(c);
    }

    public Result<Case> create(
        User currentUser,
        String title,
        String description,
        String location,
        String incidentDateStr,
        Optional<CaseStatus> status,
        Optional<String> imageUrl
    ) {
        var valRes = Validators.validateCreateCase(title, description, location, incidentDateStr);
        if (valRes.isFailure()) {
            return Result.fail(((Result.Failure<Instant>) valRes).error());
        }

        Instant incidentDate = ((Result.Success<Instant>) valRes).value();
        Instant now = Instant.now();
        Case newCase = new Case(
            UUID.randomUUID(),
            0, // Generated by DB
            title.trim(),
            description.trim(),
            location.trim(),
            incidentDate,
            status.orElse(CaseStatus.OPEN),
            imageUrl,
            State.ACTIVE,
            currentUser.id(),
            now,
            now
        );

        Case saved = caseRepository.create(newCase);
        return Result.ok(saved);
    }

    public Result<Case> update(
        User currentUser,
        UUID id,
        String title,
        String description,
        String location,
        String incidentDateStr,
        Optional<CaseStatus> status,
        Optional<String> imageUrl
    ) {
        var existingRes = getById(currentUser, id);
        if (existingRes.isFailure()) {
            return existingRes;
        }

        var valRes = Validators.validateCreateCase(title, description, location, incidentDateStr);
        if (valRes.isFailure()) {
            return Result.fail(((Result.Failure<Instant>) valRes).error());
        }

        Case existing = ((Result.Success<Case>) existingRes).value();
        Instant incidentDate = ((Result.Success<Instant>) valRes).value();
        Case updated = new Case(
            existing.id(),
            existing.caseNumber(),
            title.trim(),
            description.trim(),
            location.trim(),
            incidentDate,
            status.orElse(existing.status()),
            imageUrl.isPresent() ? imageUrl : existing.imageUrl(),
            existing.state(),
            existing.ownerId(), // ownerId cannot be changed
            existing.createdAt(),
            Instant.now()
        );

        Case saved = caseRepository.update(updated);
        return Result.ok(saved);
    }

    public Result<Void> delete(User currentUser, UUID id) {
        var existingRes = getById(currentUser, id);
        if (existingRes.isFailure()) {
            return Result.fail(((Result.Failure<Case>) existingRes).error());
        }

        caseRepository.deactivateCascade(id);
        return Result.ok(null);
    }
}
